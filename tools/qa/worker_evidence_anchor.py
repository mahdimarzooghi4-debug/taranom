#!/usr/bin/env python3
"""TRN-TECH-155: independent, ephemeral test-only Worker evidence checkpoint.

This Python verifier is NOT invoked by the Kestrel host. A verifier-only key
and HMAC checkpoint are in a separate 0700 /tmp/taranom-anchor-* fixture.
This is not a separate OS principal or official independent custody: the
same CI runner owner can read or replace both key and files.
"""
from __future__ import annotations

import hashlib
import hmac
import json
import os
from pathlib import Path
import re
import secrets
import stat
import sys

from verify_ai_worker_evidence import verify

CONTRACT = "TRN-TECH-155"
PREFIX = "taranom-anchor-"
EXPECTED = {"contract", "anchoredCount", "anchoredEpoch",
            "anchoredDigest", "prefixSha256", "auditEvidence",
            "custodyVerified"}
GENESIS = "0" * 64


def fail(code: str):
    raise ValueError("SYNTHETIC_ANCHOR_" + code)


def unique(pairs):
    result = {}
    for name, value in pairs:
        if name in result:
            fail("DUPLICATE_FIELD")
        result[name] = value
    return result


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=True).encode("ascii")


def check_directory(folder: Path):
    if (not folder.is_absolute() or folder.parent != Path("/tmp")
            or not folder.name.startswith(PREFIX)
            or not re.fullmatch(r"taranom-anchor-[A-Za-z0-9_-]{6,64}",
                                folder.name)):
        fail("DIRECTORY")
    s = folder.lstat()
    if not stat.S_ISDIR(s.st_mode) or s.st_mode & 0o077:
        fail("DIRECTORY_PRIVILEGES")


def checked_file(path: Path, maximum: int):
    s = path.lstat()
    if (not stat.S_ISREG(s.st_mode) or s.st_nlink != 1 or
            s.st_mode & 0o077 or s.st_size <= 0 or s.st_size > maximum):
        fail("FILE_PRIVILEGES")
    data = path.read_bytes()
    if len(data) != s.st_size:
        fail("FILE_RACE")
    return data


def fresh_file(path: Path, data: bytes):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                 getattr(os, "O_NOFOLLOW", 0), 0o600)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
    except BaseException:
        # Do not repair or silently overwrite a possibly partial checkpoint.
        raise


def evidence_path():
    if os.environ.get("TARANOM_AI_WORKER_EVIDENCE_TEST_ONLY") != "CI_EPHEMERAL_ONLY":
        fail("TEST_ONLY")
    path = Path(os.environ["TARANOM_AI_WORKER_EVIDENCE_FILE"])
    if (not path.is_absolute() or path.name != "worker-evidence.jsonl"
            or path.parent.parent != Path("/tmp")
            or not path.parent.name.startswith("taranom-worker-")):
        fail("EVIDENCE_PATH")
    return path


def directory():
    if os.environ.get("TARANOM_CENTER_DEMO_TEST_ONLY") != "CI_EPHEMERAL_ONLY":
        fail("TEST_ONLY")
    raw = os.environ.get("TARANOM_AI_WORKER_ANCHOR_DIR", "")
    folder = Path(raw)
    check_directory(folder)
    return folder


def read_records():
    rows, boots, last_epoch = verify(evidence_path())
    return rows, boots, last_epoch


def prefix_digest(rows):
    return hashlib.sha256(("\n".join(rows) + "\n").encode("utf-8")
                          ).hexdigest().upper()


def anchor_payload(rows, boots, epoch):
    if len(boots) != 1 or epoch != boots[0] or len(rows) < 3:
        fail("PRE_RESTART_SHAPE")
    final = json.loads(rows[-1], object_pairs_hook=unique)
    return {
        "contract": CONTRACT,
        "anchoredCount": len(rows),
        "anchoredEpoch": epoch,
        "anchoredDigest": final["digest"],
        "prefixSha256": prefix_digest(rows),
        "auditEvidence": False,
        "custodyVerified": False,
    }


def create(folder: Path):
    check_directory(folder)
    rows, boots, epoch = read_records()
    payload = anchor_payload(rows, boots, epoch)
    # The HMAC key is generated by THIS verifier, never sent to the
    # host or signed .NET->Python worker challenge.
    secret = secrets.token_bytes(32)
    fresh_file(folder / "custodian.key", secret)
    sig = hmac.new(secret, b"TRN-TECH-155\n" + canonical(payload),
                   hashlib.sha256).hexdigest().upper()
    fresh_file(folder / "anchor.json", canonical({**payload, "mac": sig}) + b"\n")
    return payload


def verify_continuation(folder: Path):
    check_directory(folder)
    key = checked_file(folder / "custodian.key", 32)
    if len(key) != 32:
        fail("KEY")
    packed = checked_file(folder / "anchor.json", 2048)
    if not packed.endswith(b"\n"):
        fail("PARTIAL_MANIFEST")
    manifest = json.loads(packed.decode("utf-8", errors="strict"),
                          object_pairs_hook=unique)
    if not isinstance(manifest, dict) or set(manifest) != EXPECTED | {"mac"}:
        fail("MANIFEST_FIELDS")
    mac = manifest["mac"]
    if not isinstance(mac, str) or not re.fullmatch(r"[0-9A-F]{64}", mac):
        fail("MAC_SHAPE")
    payload = {k: v for k, v in manifest.items() if k != "mac"}
    if (payload["contract"] != CONTRACT or
            payload["auditEvidence"] is not False or
            payload["custodyVerified"] is not False or
            type(payload["anchoredCount"]) is not int or
            payload["anchoredCount"] < 3 or payload["anchoredCount"] > 4094 or
            not isinstance(payload["anchoredEpoch"], str) or
            not re.fullmatch(r"[0-9a-f]{32}", payload["anchoredEpoch"]) or
            any(not isinstance(payload[k], str) or
                not re.fullmatch(r"[0-9A-F]{64}", payload[k])
                for k in ("anchoredDigest", "prefixSha256")) or
            packed != canonical(manifest) + b"\n"):
        fail("MANIFEST_INVALID")
    proof = hmac.new(key, b"TRN-TECH-155\n" + canonical(payload),
                     hashlib.sha256).hexdigest().upper()
    if not hmac.compare_digest(proof, mac):
        fail("BAD_MAC")

    rows, boots, latest_epoch = read_records()
    n = payload["anchoredCount"]
    if (len(rows) != n + 2 or len(boots) != 2 or
            boots[0] != payload["anchoredEpoch"] or
            boots[1] == boots[0] or latest_epoch != boots[1] or
            prefix_digest(rows[:n]) != payload["prefixSha256"]):
        fail("PREFIX_OR_RESTART_CHANGED")
    anchored = json.loads(rows[n-1], object_pairs_hook=unique)
    boot = json.loads(rows[n], object_pairs_hook=unique)
    recovery = json.loads(rows[n+1], object_pairs_hook=unique)
    if (anchored["digest"] != payload["anchoredDigest"] or
            anchored["epoch"] != payload["anchoredEpoch"] or
            boot["kind"] != "Boot" or boot["epoch"] != boots[1] or
            boot["previousDigest"] != payload["anchoredDigest"] or
            recovery["kind"] != "Success" or recovery["epoch"] != boots[1]):
        fail("RESTART_LINEAGE")
    return {"anchoredCount": n, "newEpochValidated": True,
            "auditEvidence": False, "custodyVerified": False,
            "productionReady": False}


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in {"create", "verify"}:
        fail("COMMAND")
    folder = directory()
    if sys.argv[1] == "create":
        create(folder)
        print("PASS: bounded verifier-held synthetic evidence checkpoint; "
              "no independent custody or Production authority")
    else:
        verify_continuation(folder)
        print("PASS: independent HMAC checkpoint rejected ledger rehash/truncation "
              "and verified actual two-epoch Worker continuation; no legal audit")


if __name__ == "__main__":
    try:
        main()
    except (AssertionError, OSError, ValueError, KeyError, UnicodeError,
            json.JSONDecodeError) as ex:
        # Never print verifier key, manifest body, request or Worker data.
        print("SYNTHETIC_ANCHOR_VERIFICATION_DENIED",
              file=sys.stderr)
        raise SystemExit(17) from None
